function parseFrontmatter(raw) {
  const match = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!match) throw new Error('No frontmatter found')
  const [, fm, body] = match
  const data = {}
  for (const line of fm.split('\n')) {
    const m = line.match(/^([a-zA-Z]+):\s*"(.*)"$/)
    if (m) data[m[1]] = m[2].replace(/\\"/g, '"')
  }
  return { data, body }
}

function splitSections(body) {
  const relatedIdx = body.indexOf('## Related Reading')
  const faqIdx = body.indexOf('## Frequently Asked Questions')
  const main = body.slice(0, relatedIdx > -1 ? relatedIdx : faqIdx).trim()
  const relatedRaw = relatedIdx > -1 ? body.slice(relatedIdx, faqIdx).trim() : ''
  const faqRaw = body.slice(faqIdx).trim()
  return { main, relatedRaw, faqRaw }
}

function parseRelated(relatedRaw) {
  const items = []
  const re = /-\s*\[([^\]]+)\]\(([^)]+)\)/g
  let m
  while ((m = re.exec(relatedRaw))) {
    items.push({ text: m[1], href: m[2] })
  }
  return items
}

function parseFaqs(faqRaw) {
  const lines = faqRaw.split('\n').slice(1) // drop the "## Frequently Asked Questions" heading
  const faqs = []
  let current = null
  for (const line of lines) {
    const qMatch = line.match(/^\*\*(.+?)\*\*$/)
    if (qMatch) {
      if (current) faqs.push(current)
      current = { question: qMatch[1], answer: '' }
    } else if (current && line.trim()) {
      current.answer = (current.answer ? current.answer + ' ' : '') + line.trim()
    }
  }
  if (current) faqs.push(current)
  // FAQ answers render as plain text, not HTML — strip any stray markdown link syntax down to just the link text
  for (const faq of faqs) {
    faq.answer = faq.answer.replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
  }
  return faqs
}

const files = fs.readdirSync(draftsDir).filter((f) => f.endsWith('.md')).sort()
const posts = []

files.forEach((file, i) => {
  const raw = fs.readFileSync(path.join(draftsDir, file), 'utf8')
  const { data, body } = parseFrontmatter(raw)
  const { main, relatedRaw, faqRaw } = splitSections(body)
  const bodyHtml = marked.parse(main)
  const related = parseRelated(relatedRaw)
  const faqs = parseFaqs(faqRaw)

  posts.push({
    slug: data.slug,
    title: data.title,
    seotitle: data.seotitle,
    seodescription: data.seodescription,
    seokeywords: data.seokeywords,
    category: data.category,
    image: SLUG_IMAGE[data.slug] || IMAGES.marrakech,
    publishedAt: PUBLISH_DATES[i] || '2026-08-01',
    bodyHtml,
    related,
    faqs,
  })
})

// --- write data/localBlogPosts.ts ---
const tsLiteral = (v) => JSON.stringify(v)
const dataFileContent = `// AUTO-GENERATED by scripts/generate-static-blog-posts.mjs — do not edit by hand.
// Regenerate by editing the source markdown in content/blog-drafts/ and re-running the script.
export interface LocalBlogPost {
  slug: string
  title: string
  seotitle: string
  seodescription: string
  seokeywords: string
  category: string
  image: string
  publishedAt: string
  bodyHtml: string
  related: { text: string; href: string }[]
  faqs: { question: string; answer: string }[]
}

export const localBlogPosts: LocalBlogPost[] = ${JSON.stringify(posts, null, 2)}

export function getLocalBlogPost(slug: string): LocalBlogPost | undefined {
  return localBlogPosts.find((p) => p.slug === slug)
}
`
fs.writeFileSync(path.join(dataDir, 'localBlogPosts.ts'), dataFileContent, 'utf8')

// --- write one thin page per post ---
for (const post of posts) {
  const pageContent = `// AUTO-GENERATED by scripts/generate-static-blog-posts.mjs — do not edit by hand.
import { getLocalBlogPost } from '../../data/localBlogPosts'
import StaticBlogPost from '../../components/StaticBlogPost'

const post = getLocalBlogPost(${tsLiteral(post.slug)})!

export default function Page() {
  return <StaticBlogPost post={post} />
}
`
  fs.writeFileSync(path.join(pagesDir, `${post.slug}.tsx`), pageContent, 'utf8')
}

